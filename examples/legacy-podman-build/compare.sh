#!/usr/bin/env bash
# =============================================================================
# Build the SAME EE two ways and compare build time, image size and content:
#
#   legacy     : examples/legacy-podman-build/Containerfile via "podman build"
#   ours       : ee_definitions/examples/ee-winrm-kerberos-rhel8_v1.0.0.yml via build_ee.yml
#   ours-lean  : the same definition without the build-only (compile) packages,
#                which this base image doesn't need (it already ships
#                pywinrm + pykerberos)
#
# Every build runs with caching disabled. Run from the repo root on the
# EE Builder VM, after "podman login registry.redhat.io":
#
#   ROUNDS=2 examples/legacy-podman-build/compare.sh | tee compare-results.md
#
# Build-host substitutions, applied to the LEGACY build only because the
# recommended definition is already portable:
#   * ubi.repo is kept: the original deletes it and relies on the build host's
#     RHEL subscription repos, which a plain podman host doesn't have.
#   * python3-devel -> python36-devel: what python3-devel resolves to on RHEL 8.
#   * git-subtree   -> git: git-subtree is only in RHEL repos, not UBI.
# =============================================================================
set -euo pipefail

ROUNDS="${ROUNDS:-2}"
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
LEGACY_SRC="$REPO/examples/legacy-podman-build"
EE_FILE="ee_definitions/examples/ee-winrm-kerberos-rhel8_v1.0.0.yml"
BASE="registry.redhat.io/ansible-automation-platform-24/ee-minimal-rhel8:1.0.0-965"
WORK="$(mktemp -d /tmp/ee-compare.XXXXXX)"
trap 'rm -rf "$WORK"' EXIT
log() { echo "[$(date +%H:%M:%S)] $*" >&2; }

cd "$REPO"
podman image exists "$BASE" || podman pull "$BASE" >&2

# ---- Legacy build context (_build/ is what the original Containerfile expects)
log "Preparing legacy build context"
mkdir -p "$WORK/legacy/_build/scripts" "$WORK/wheel"
cp "$LEGACY_SRC"/{Containerfile,pip.conf,ca-bundle.crt,krb5.conf} "$WORK/legacy/"
cp "$LEGACY_SRC/requirements.txt" "$WORK/legacy/_build/"
sed -e 's/^python3-devel /python36-devel /' -e 's/^git-subtree /git /' \
  "$LEGACY_SRC/bindep.txt" > "$WORK/legacy/_build/bindep.txt"
sed -i 's|^RUN rm -f /etc/yum.repos.d/ubi.repo|RUN true  # ubi.repo kept: no RHEL subscription on this host|' \
  "$WORK/legacy/Containerfile"
# The original was generated by ansible-builder 3.0.x (requirements-parser + --sanitize).
# Fetch its helper scripts from the published wheel (wheel only: no code is run).
python3 -m pip download -q --no-deps --only-binary=:all: 'ansible-builder==3.0.1' -d "$WORK/wheel" >&2
python3 -I - "$WORK/wheel" "$WORK/legacy/_build/scripts" <<'PY'
import os, sys, zipfile
whl = [f for f in os.listdir(sys.argv[1]) if f.endswith('.whl')][0]
z = zipfile.ZipFile(os.path.join(sys.argv[1], whl))
for n in z.namelist():
    if '/_target_scripts/' in n and not n.endswith('__init__.py'):
        p = os.path.join(sys.argv[2], os.path.basename(n))
        open(p, 'wb').write(z.read(n)); os.chmod(p, 0o755)
PY

# ---- Lean variant: identical definition minus "[platform:rpm compile]" packages
grep -v 'compile\]' "$EE_FILE" > "$WORK/ee-winrm-kerberos-lean_v1.0.0.yml"

PLAYBOOK_OPTS=(-e push=false
  -e '{"ee_update_base_images": false, "ee_pull_collections_from_hub": false, "ee_extra_build_cli_args": "--no-cache"}')

build() {  # $1 = variant; prints elapsed seconds
  local start end
  start=$(date +%s.%N)
  case "$1" in
    legacy)    (cd "$WORK/legacy" && podman build --no-cache -f Containerfile -t localhost/ee-winrm-legacy:test . ) > "$WORK/$1.log" 2>&1 ;;
    ours)      ansible-playbook build_ee.yml -e "ee_file=$EE_FILE" "${PLAYBOOK_OPTS[@]}" > "$WORK/$1.log" 2>&1 ;;
    ours-lean) ansible-playbook build_ee.yml -e "ee_file=$WORK/ee-winrm-kerberos-lean_v1.0.0.yml" "${PLAYBOOK_OPTS[@]}" > "$WORK/$1.log" 2>&1 ;;
  esac || { log "BUILD FAILED: $1 (log follows)"; tail -40 "$WORK/$1.log" >&2; exit 1; }
  end=$(date +%s.%N)
  echo "$end - $start" | bc
}
image_of() {
  case "$1" in
    legacy) echo localhost/ee-winrm-legacy:test ;;
    ours) echo localhost/ee-winrm-kerberos-rhel8:1.0.0 ;;
    ours-lean) echo localhost/ee-winrm-kerberos-lean:1.0.0 ;;
  esac
}

VARIANTS=(legacy ours ours-lean)
declare -A TIMES
for r in $(seq 1 "$ROUNDS"); do
  for v in "${VARIANTS[@]}"; do
    podman rmi -f "$(image_of "$v")" >/dev/null 2>&1 || true
    log "Round $r/$ROUNDS: building $v ..."
    t=$(build "$v")
    TIMES[$v]="${TIMES[$v]:-} $t"
    log "Round $r/$ROUNDS: $v took ${t}s"
  done
done

avg() { echo "$*" | tr ' ' '\n' | grep . | awk '{s+=$1; n++} END {printf "%.0f", s/n}'; }
mb()  { awk -v b="$1" 'BEGIN {printf "%.0f", b/1000000}'; }

echo "## Results ($ROUNDS round(s), no build cache, $(date -u +%Y-%m-%dT%H:%MZ))"
echo
echo "Base image: \`$BASE\` ($(mb "$(podman image inspect "$BASE" --format '{{.Size}}')") MB, $(podman run --rm --entrypoint bash "$BASE" -c 'rpm -qa | wc -l') RPMs)"
echo
echo "| Metric | legacy (podman build) | ours | ours-lean |"
echo "| :-- | --: | --: | --: |"
row() { printf '| %s | %s | %s | %s |\n' "$1" "$2" "$3" "$4"; }
declare -A SIZE GZ LAYERS USERS RPMS
for v in "${VARIANTS[@]}"; do
  img=$(image_of "$v")
  SIZE[$v]=$(mb "$(podman image inspect "$img" --format '{{.Size}}')")
  GZ[$v]=$(mb "$(podman save "$img" 2>/dev/null | gzip -6 | wc -c)")
  LAYERS[$v]=$(podman image inspect "$img" --format '{{len .RootFS.Layers}}')
  USERS[$v]=$(podman run --rm "$img" id -un 2>/dev/null)
  RPMS[$v]=$(podman run --rm "$img" bash -c 'rpm -qa | wc -l')
done
row "Build time, average (s)"       "$(avg ${TIMES[legacy]})" "$(avg ${TIMES[ours]})" "$(avg ${TIMES[ours-lean]})"
row "Build times per round (s)"     "$(echo ${TIMES[legacy]} | xargs printf '%.0f ')" "$(echo ${TIMES[ours]} | xargs printf '%.0f ')" "$(echo ${TIMES[ours-lean]} | xargs printf '%.0f ')"
row "Image size, uncompressed (MB)" "${SIZE[legacy]}" "${SIZE[ours]}" "${SIZE[ours-lean]}"
row "Image size, gzip ~ pull (MB)"  "${GZ[legacy]}" "${GZ[ours]}" "${GZ[ours-lean]}"
row "Layers"                        "${LAYERS[legacy]}" "${LAYERS[ours]}" "${LAYERS[ours-lean]}"
row "Runs as user"                  "${USERS[legacy]}" "${USERS[ours]}" "${USERS[ours-lean]}"
row "RPMs installed"                "${RPMS[legacy]}" "${RPMS[ours]}" "${RPMS[ours-lean]}"

check() {  # $1 = label, $2 = command; prints a row of ✅/❌ per variant
  local cells=()
  for v in "${VARIANTS[@]}"; do
    if podman run --rm "$(image_of "$v")" bash -c "$2" >/dev/null 2>&1; then cells+=("✅"); else cells+=("❌"); fi
  done
  row "$1" "${cells[@]}"
}
echo
echo "| Check | legacy | ours | ours-lean |"
echo "| :-- | :-: | :-: | :-: |"
check "ansible + ansible-runner work"            'ansible --version && ansible-runner --version'
check "import winrm, kerberos, jmespath"         'python3 -c "import winrm, kerberos, jmespath"'
check "kinit available"                          'command -v kinit'
check "git available"                            'git --version'
check "corporate CA trusted"                     'trust list | grep -q "Example Corp Root CA"'
check "krb5.conf in place"                       'grep -q EXAMPLE.COM /etc/krb5.conf'
check "pip.conf in place"                        'test -f /etc/pip.conf'
check "NO gcc in image"                          '! rpm -q gcc'
check "NO krb5-devel in image"                   '! rpm -q krb5-devel'
check "NO extra Python 3.6 (python36) in image"  '! rpm -q python36'
check "NOT running as root"                      'test "$(id -u)" != 0'
log "Done."
